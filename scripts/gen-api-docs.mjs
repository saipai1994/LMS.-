// Generates docs/API.md from the NestJS controllers so the route inventory cannot drift from the code.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const root = 'apps/api/src';
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : p.endsWith('.controller.ts') && files.push(p); } })(root);
const rows = [];
for (const f of files.sort()) {
  const src = readFileSync(f, 'utf8');
  const prefix = (src.match(/@Controller\('([^']*)'\)/) ?? src.match(/@Controller\(\)/) ? (src.match(/@Controller\('([^']*)'\)/)?.[1] ?? '') : '');
  const isPublicClass = /@Controller\([^)]*\)\s*\n@Public\(\)/.test(src);
  const re = /((?:@(?:Public|AllowWithoutMfa|HttpCode)\([^)]*\)\s*)*)@(Get|Post|Put|Patch|Delete)\('([^']*)'\)((?:\s*@(?:Public|AllowWithoutMfa|HttpCode)\([^)]*\))*)/g;
  let m;
  while ((m = re.exec(src))) {
    const deco = `${m[1]}${m[4]}`;
    const body = src.slice(m.index, m.index + 900).split(/\n  @(?:Get|Post|Put|Patch)\(/)[0];
    const perms = [...new Set([...body.matchAll(/(?:needs|can|campusScope)\(a, '([a-z_.]+)'/g)].map((x) => x[1]))];
    const path = '/' + [prefix, m[3]].filter(Boolean).join('/').replace(/\/+/g, '/');
    const access = /@Public\(\)/.test(deco) || isPublicClass ? 'public' : /x-platform-token/.test(body) ? 'platform token' : perms.length ? perms.join(', ') : 'signed-in (resource-level checks)';
    rows.push([path, m[2].toUpperCase(), access, f.replace('apps/api/src/', '')]);
  }
}
rows.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
const out = `# API reference

_Generated by \`node scripts/gen-api-docs.mjs\` from the controllers (${rows.length} routes). Do not edit by hand._

**Conventions.** JSON over HTTP. Authenticate with \`Authorization: Bearer <token>\` from \`POST /auth/login\`. Errors are \`{ "error": "<code>", ... }\`
(validation: \`400 validation_failed\` with \`issues[]\`; \`401\` unauthenticated; \`403\` forbidden/\`mfa_setup_required\`/\`feature_not_in_plan\`;
\`404\` not found *or not visible to you*; \`409\` state conflict; \`422\` business-rule violation; \`429\` rate limited). Money is integer minor units (paise).
Lists accept \`limit\`/\`offset\` where documented. "Access" lists the permission(s) the handler checks (campus-scoped); resource-level rules
(guardian link, own course, own record) are enforced in addition and are described in docs/SECURITY.md.

| Route | Method | Access | Source |
|---|---|---|---|
${rows.map((r) => `| \`${r[0]}\` | ${r[1]} | ${r[2]} | ${r[3]} |`).join('\n')}
`;
writeFileSync('docs/API.md', out);
console.log(`wrote docs/API.md with ${rows.length} routes`);
